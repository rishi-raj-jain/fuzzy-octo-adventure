// Writes one run endpoint per Vercel region: src/app/api/regions/<code>/runs/route.ts.
// Each region needs its own route file because a function can only be pinned to regions as a whole
// (vercel.ts pins the ones listed in NAVPROBE_REGIONS). Run after changing REGIONS: npm run regions:generate
import { mkdir, readdir, rm, writeFile } from 'node:fs/promises'
import { REGIONS } from '../src/lib/regions.ts'

const root = new URL('../src/app/api/regions/', import.meta.url)

for (const entry of await readdir(root).catch(() => [])) {
  if (!(entry in REGIONS)) await rm(new URL(`${entry}/`, root), { recursive: true })
}

for (const [code, location] of Object.entries(REGIONS)) {
  const dir = new URL(`${code}/runs/`, root)
  await mkdir(dir, { recursive: true })
  await writeFile(
    new URL('route.ts', dir),
    `// Generated by scripts/generate-region-routes.mjs. Runs in ${code} (${location}) when NAVPROBE_REGIONS includes it.
import { runScenarioRequest } from '@/lib/run-handler'

export const runtime = 'nodejs'
export const maxDuration = 300

export function POST(req: Request) {
  return runScenarioRequest(req, '${code}')
}
`,
  )
}
console.log(`Wrote ${Object.keys(REGIONS).length} region routes`)
